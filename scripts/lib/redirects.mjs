/**
 * Legacy-domain migration table, parsed from the delivered REDIRECTIONS.md so
 * the generated .htaccess rules and the automated test read the same source.
 */
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';

export const REDIRECTIONS_MD = 'design/uploads/floraconcept-livraison-dev-2026-10-08/REDIRECTIONS.md';

/**
 * The delivered table still carries draft targets that are not slugs of the
 * approved site map (SITE-MAP-DEV.md, 06/10/2026). Each is mapped to the closest
 * approved page and reported as « to confirm » by the client.
 */
export const TARGET_MAP = {
  '/location-plantes-bureaux/': '/location-plantes-bureau/',
  '/contact/': '/devis/',
  '/confidentialite/': '/politique-de-confidentialite/',
  '/agences/paris/': '/location-entretien-plantes-bureau-paris/',
  '/cadres-vegetaux-stabilises/': '/cadres-vegetaux-plantes-stabilisees/',
};

/**
 * Targets the table left « à fixer », decided from the content of the old pages
 * (checked 25/10/2026): the old « Bouquets de fleurs naturelles / artificielles »
 * page is about office flower bouquets, so it goes to the flower subscription page.
 */
export const FROM_OVERRIDES = {
  'vegetaloffice.fr/bouquets-fleurs-naturelles-artificielles/': '/abonnement-fleurs-entreprise/',
};

const DOMAINS = { 'floraconcept.com': /^## floraconcept\.com/, 'vegetaloffice.fr': /^## vegetaloffice\.fr \(28/ };

export async function loadRedirects(root) {
  const md = await readFile(join(root, REDIRECTIONS_MD), 'utf8');
  const rules = [];
  let domain = null;
  for (const line of md.split('\n')) {
    if (line.startsWith('## ')) {
      domain = Object.entries(DOMAINS).find(([, re]) => re.test(line))?.[0] ?? null;
      continue;
    }
    if (!domain) continue;
    const m = line.match(/^\|\s*`([^`]+)`\s*\|\s*(.*?)\s*\|\s*(301|410)\s*\|$/);
    if (!m) continue;
    const [, from, targetCell, code] = m;
    const raw = (targetCell.match(/`<FR>([^`]*)`/) || [])[1] ?? null;
    const draft = /à fixer/.test(targetCell);
    const override = FROM_OVERRIDES[domain + from];
    const target = override ?? (raw ? (TARGET_MAP[raw] ?? raw) : null);
    rules.push({
      domain,
      from,
      code: Number(code),
      target,
      ...(raw && (draft || TARGET_MAP[raw] || override) ? { decision: raw === target ? 'draft target kept (content matches)' : `draft ${raw} → ${target}` } : {}),
    });
  }
  return rules;
}

/** Spam slugs (385, from crawl-vegetaloffice.csv) are added to redirects/vegetaloffice-spam.txt, one per line. */
export async function loadSpamSlugs(root) {
  try {
    const txt = await readFile(join(root, 'redirects/vegetaloffice-spam.txt'), 'utf8');
    return txt.split('\n').map((l) => l.trim()).filter((l) => l && !l.startsWith('#'));
  } catch {
    return [];
  }
}

const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/** mod_rewrite rules for one legacy domain: page-by-page first, catch-all last. */
export function htaccessFor(domain, rules, siteUrl, spam = []) {
  const own = rules.filter((r) => r.domain === domain);
  const lines = [
    `# ${domain} → ${siteUrl}`,
    '# Generated by scripts/postbuild.mjs from REDIRECTIONS.md: do not edit by hand.',
    'RewriteEngine On',
    '',
  ];
  for (const r of own) {
    const path = r.from.replace(/^\//, '').replace(/\/$/, '');
    const pattern = path ? `^${esc(path)}/?$` : '^$';
    if (r.code === 410) lines.push(`RewriteRule ${pattern} - [G,L]`);
    else lines.push(`RewriteRule ${pattern} ${siteUrl}${r.target} [R=301,L]`);
  }
  if (domain === 'vegetaloffice.fr') {
    lines.push('', '# Hack spam (old site compromise): 410 Gone');
    lines.push('RewriteRule ^[0-9]+-2/?$ - [G,L]');
    lines.push('# Encoded non-ASCII slugs (Greek, Cyrillic…): no legitimate URL of the old site has one');
    lines.push('RewriteCond %{THE_REQUEST} \\s/[^?\\s]*%[89a-fA-F][0-9a-fA-F]');
    lines.push('RewriteRule ^ - [G,L]');
    for (const s of spam) lines.push(`RewriteRule ^${esc(s.replace(/^\/|\/$/g, ''))}/?$ - [G,L]`);
  }
  lines.push('', '# Everything else (only after the page-by-page rules)', `RewriteRule ^ ${siteUrl}/ [R=301,L]`, '');
  return lines.join('\n');
}
